#include "ntc.h"
#include "adc.h"
#include "stm32f3xx_hal.h"
#include <math.h>
#include "adc_cache.h"

/* =============================================================================
 * Настройки NTC термистора (под твой датчик)
 * =============================================================================
 * R_fixed  – резистор делителя (Ом)
 * R0       – сопротивление NTC при 25°C
 * BETA     – коэффициент бета (обычно 3950)
 * T0_K     – 25°C в Кельвинах
 */
#define NTC_R_FIXED   10000.0f
#define NTC_R0         4700.0f
#define NTC_BETA       3950.0f
#define NTC_T0_K       298.15f

/* =============================================================================
 * Настройки фильтрации
 * =============================================================================
 * MAX_TEMP_JUMP      – максимально допустимый скачок температуры за один
 *                      цикл опроса (градусы). Если новое значение отличается
 *                      сильнее – считаем это помехой и ограничиваем шаг.
 *
 * FILTER_COEFF       – коэффициент сглаживания IIR (0.95 = новое значение
 *                      влияет всего на 5%). Чем ближе к 1.0, тем сильнее
 *                      фильтрация, но больше запаздывание.
 *
 * MEDIAN_SIZE        – размер окна медианного фильтра (должен быть нечётным).
 *                      Медиана отлично режет одиночные выбросы.
 */
#define MAX_TEMP_JUMP    2.5f
#define FILTER_COEFF     0.95f    // 0.95 = новое значение вносит 5% веса
#define MEDIAN_SIZE      5         // 3, 5 или 7 – чем больше, тем сильнее сглаживание

/* -----------------------------------------------------------------------------
 * Статические переменные для фильтров
 * -----------------------------------------------------------------------------
 * raw_buffer   – кольцевой буфер для медианного фильтра
 * raw_index    – текущая позиция записи в буфер
 * filtered     – отфильтрованное значение температуры
 * first_sample – флаг первого запуска (для инициализации фильтра)
 */
static int16_t raw_buffer[MEDIAN_SIZE] = {0};
static uint8_t raw_index = 0;
static float filtered = 0.0f;
static uint8_t first_sample = 1;

/* =============================================================================
 * Вспомогательная функция – быстрая сортировка для медианы (сеть Хана)
 * =============================================================================
 * Сортирует массив arr из n элементов по возрастанию (простой пузырёк,
 * но для n <= 7 это быстрее и проще любых сложных алгоритмов).
 */
static void sort_array(int16_t *arr, uint8_t n)
{
    for (uint8_t i = 0; i < n - 1; i++) {
        for (uint8_t j = i + 1; j < n; j++) {
            if (arr[i] > arr[j]) {
                int16_t tmp = arr[i];
                arr[i] = arr[j];
                arr[j] = tmp;
            }
        }
    }
}

/* =============================================================================
 * Преобразование сырого ADC в температуру (без фильтрации)
 * =============================================================================
 * 1. Получаем напряжение на делителе (0..3.3В)
 * 2. Вычисляем сопротивление NTC
 * 3. Применяем бета-уравнение для получения температуры в °C
 */
static float raw_adc_to_temp_c(uint16_t adc_value)
{
    // Защита от деления на ноль (если АЦП не подключен)
    if (adc_value == 0) return -50.0f;
    if (adc_value >= 4095) return 150.0f;

    // Напряжение в долях от опорного (3.3В)
    float v_ratio = (float)adc_value / 4095.0f;

    // Сопротивление NTC: R_fixed * V_ratio / (1 - V_ratio)
    float r_ntc = (NTC_R_FIXED * v_ratio) / (1.0f - v_ratio);

    // Бета-уравнение: 1/T = 1/T0 + (1/BETA) * ln(R_ntc / R0)
    float inv_t = (1.0f / NTC_T0_K) + (1.0f / NTC_BETA) * logf(r_ntc / NTC_R0);
    float temp_k = 1.0f / inv_t;

    // Переводим в градусы Цельсия
    return temp_k - 273.15f;
}

/* =============================================================================
 * Публичная функция – получить стабильную температуру
 * =============================================================================
 * Вызывается из main (обычно раз в 2000 мс или реже).
 * Возвращает температуру в градусах Цельсия с фиксированием до целых.
 */
int16_t NTC_ReadTempC(void)
{
    // 1. Получаем сырой отсчёт АЦП (уже усреднённый аппаратно или в adc_cache)
    uint16_t raw_adc = ADC_GetNTC_Raw();

    // 2. Преобразуем в температуру (пока без фильтрации)
    float raw_temp = raw_adc_to_temp_c(raw_adc);

    // 3. Медианный фильтр (копим в буфере, берём средний элемент)
    raw_buffer[raw_index++] = (int16_t)raw_temp;   // округляем до целого для буфера
    if (raw_index >= MEDIAN_SIZE) raw_index = 0;

    int16_t sorted[MEDIAN_SIZE];
    for (uint8_t i = 0; i < MEDIAN_SIZE; i++) sorted[i] = raw_buffer[i];
    sort_array(sorted, MEDIAN_SIZE);
    float median_temp = (float)sorted[MEDIAN_SIZE / 2];   // центральный элемент

    // 4. Первый запуск – просто запоминаем значение
    if (first_sample) {
        filtered = median_temp;
        first_sample = 0;
        return (int16_t)(filtered + 0.5f);
    }

    // 5. Ограничиваем скорость изменения (отбрасывание резких выбросов)
    float delta = median_temp - filtered;
    if (delta > MAX_TEMP_JUMP)  delta = MAX_TEMP_JUMP;
    if (delta < -MAX_TEMP_JUMP) delta = -MAX_TEMP_JUMP;

    // 6. IIR-фильтр с коэффициентом FILTER_COEFF
    filtered = filtered * FILTER_COEFF + (filtered + delta) * (1.0f - FILTER_COEFF);

    // 7. Возвращаем целое значение (округление)
    return (int16_t)(filtered + 0.5f);
}

/* =============================================================================
 * Блокирующее чтение (для калибровки/отладки)
 * =============================================================================
 * Читает ADC напрямую, усредняет по NTC_SAMPLES, возвращает float.
 * В основном проекте не используется, но может пригодиться для настройки.
 */
float NTC_ReadTempC_Blocking(void)
{
    #define NTC_SAMPLES 16u
    uint32_t sum = 0;
    for (uint32_t i = 0; i < NTC_SAMPLES; i++) {
        HAL_ADC_Start(&hadc1);
        HAL_ADC_PollForConversion(&hadc1, 10);
        sum += HAL_ADC_GetValue(&hadc1);
        HAL_ADC_Stop(&hadc1);
    }
    uint16_t avg_adc = (uint16_t)(sum / NTC_SAMPLES);
    return raw_adc_to_temp_c(avg_adc);
}
